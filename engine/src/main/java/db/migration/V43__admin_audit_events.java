package db.migration;

import java.sql.Statement;
import org.flywaydb.core.api.migration.BaseJavaMigration;
import org.flywaydb.core.api.migration.Context;

/**
 * S10: the administration audit trail. One row per administrative action, written in
 * the transaction of the change it describes ({@code SUCCESS}) or in its own
 * transaction when the call is refused ({@code DENIED}). Rows are never changed or
 * removed: the application has no update or delete path, and on PostgreSQL a trigger
 * refuses UPDATE, DELETE and TRUNCATE for every role, the table owner included.
 *
 * <p>A Java migration because the trigger is PostgreSQL only; the table and its
 * indexes are portable SQL (H2 is a development convenience and has no trigger).
 */
public class V43__admin_audit_events extends BaseJavaMigration {

    private static final String[] PORTABLE = {
        """
        CREATE TABLE admin_audit_events (
            id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            occurred_at        TIMESTAMP WITH TIME ZONE NOT NULL,
            actor              VARCHAR(255)  NOT NULL,
            actor_principal_id VARCHAR(255),
            actor_roles        VARCHAR(2000),
            action             VARCHAR(64)   NOT NULL,
            target_type        VARCHAR(64)   NOT NULL,
            target_id          VARCHAR(255),
            project_id         VARCHAR(255),
            outcome            VARCHAR(16)   NOT NULL,
            trace_id           VARCHAR(64),
            client_ip          VARCHAR(64),
            details_json       TEXT,
            CONSTRAINT ck_admin_audit_events_outcome CHECK (outcome IN ('SUCCESS', 'DENIED'))
        )
        """,
        // Newest first is the only order; every filter narrows that scan.
        "CREATE INDEX idx_admin_audit_occurred ON admin_audit_events (occurred_at)",
        "CREATE INDEX idx_admin_audit_actor ON admin_audit_events (actor, id)",
        "CREATE INDEX idx_admin_audit_action ON admin_audit_events (action, id)",
        "CREATE INDEX idx_admin_audit_project ON admin_audit_events (project_id, id)",
        "CREATE INDEX idx_admin_audit_target ON admin_audit_events (target_type, target_id, id)"
    };

    private static final String[] POSTGRES_APPEND_ONLY = {
        """
        CREATE FUNCTION admin_audit_events_append_only() RETURNS trigger
        LANGUAGE plpgsql AS $$
        BEGIN
            RAISE EXCEPTION 'admin_audit_events is append-only (% refused)', TG_OP
                USING ERRCODE = 'insufficient_privilege';
        END
        $$
        """,
        """
        CREATE TRIGGER admin_audit_events_no_change
            BEFORE UPDATE OR DELETE ON admin_audit_events
            FOR EACH ROW EXECUTE FUNCTION admin_audit_events_append_only()
        """,
        """
        CREATE TRIGGER admin_audit_events_no_truncate
            BEFORE TRUNCATE ON admin_audit_events
            FOR EACH STATEMENT EXECUTE FUNCTION admin_audit_events_append_only()
        """
    };

    @Override
    public void migrate(Context context) throws Exception {
        boolean postgres = context.getConnection().getMetaData().getDatabaseProductName()
                .toLowerCase(java.util.Locale.ROOT).contains("postgres");
        try (Statement statement = context.getConnection().createStatement()) {
            for (String sql : PORTABLE) statement.execute(sql);
            if (postgres) {
                for (String sql : POSTGRES_APPEND_ONLY) statement.execute(sql);
            }
        }
    }
}
